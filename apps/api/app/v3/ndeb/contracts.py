@dataclass(frozen=True)
class NdebAuthorizedContext:
    tenant_id: str | None
    engagement_id: str | None
    classification: Mapping[str, JsonValue] | None = None


@dataclass(frozen=True, order=True)
class NdebValidationIssue:
    code: NdebIssueCode
    json_pointer: str


@dataclass(frozen=True)
class NdebValidationResult:
    disposition: NdebDisposition
    issues: tuple[NdebValidationIssue, ...]
    validated_bundle: Mapping[str, JsonValue] | None
    computed_digest_sha256: str | None
